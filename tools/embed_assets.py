"""Index runtime assets and emit Windows RCDATA for a standalone executable.

Only publishing builds run this generator. Assets remain individual RCDATA
resources, so loading uses the executable's mapped memory without extracting
anything to disk. The generated C++ table contains paths/resource IDs only.

Usage: python tools/embed_assets.py --root . --output <build>/generated/embedded_assets
       [--notices <build>/THIRD_PARTY_NOTICES.txt]
"""

import argparse
import hashlib
import json
from pathlib import Path


def is_runtime_asset(path):
    """Keep every authored asset and license, excluding editor/backup files."""
    return not any(part.startswith(".") for part in path.parts) and not (
        path.name.endswith("~") or path.suffix.lower() in {".bak", ".tmp", ".orig", ".rej"}
    )


def write_if_changed(path, content):
    if not path.exists() or path.read_text(encoding="utf-8") != content:
        with path.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)


def generate(root, output, notices=None):
    root = root.resolve(strict=True)
    asset_directory = root / "assets"
    if not asset_directory.is_dir():
        raise ValueError(f"asset directory is missing: {asset_directory}")
    resources = {
        path.relative_to(root).as_posix(): path.resolve(strict=True)
        for path in asset_directory.rglob("*")
        if path.is_file() and is_runtime_asset(path.relative_to(asset_directory))
    }
    if not resources:
        raise ValueError("no runtime assets were found")
    if notices is not None:
        resources["licenses/THIRD_PARTY_NOTICES.txt"] = notices.resolve(strict=True)
    if len(resources) > 64536:
        raise ValueError("too many assets for Windows integer resource IDs")

    output.mkdir(parents=True, exist_ok=True)
    rows = []
    rc_lines = ["// Generated by tools/embed_assets.py; do not edit.",
                "#pragma code_page(65001)",
                "#include <winres.h>", "LANGUAGE LANG_NEUTRAL, SUBLANG_NEUTRAL", ""]
    manifest = []
    for resource_id, (name, source) in enumerate(sorted(resources.items()), start=1000):
        # JSON string escaping also forms a C++ string literal. Keep Unicode as
        # UTF-8 bytes rather than JSON surrogate pairs (invalid C++ escapes).
        encoded_name = json.dumps(name, ensure_ascii=False)
        rows.append(f"    {{{encoded_name}, {resource_id}}},")
        # rc.exe accepts forward slashes in absolute paths. Escape quotes and
        # backslashes explicitly instead of passing paths through the shell.
        encoded_source = str(source).replace("\\", "/").replace('"', '\\"')
        data = source.read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        # Content changes must update the RC's timestamp even when source paths
        # are unchanged, so the build reliably recompiles the resource object.
        rc_lines.append(f"// SHA-256: {digest}")
        rc_lines.append(f'{resource_id} RCDATA "{encoded_source}"')
        manifest.append({"path": name, "resource_id": resource_id, "bytes": len(data),
                         "sha256": digest})

    header = "\n".join([
        "// Generated by tools/embed_assets.py; do not edit.", "#pragma once", "",
        "#include <array>", "#include <string_view>", "",
        "namespace immune::platform::detail {", "",
        "struct EmbeddedAssetEntry {", "    std::string_view path;",
        "    unsigned short resource_id;", "};", "",
        f"inline constexpr std::array<EmbeddedAssetEntry, {len(rows)}> kEmbeddedAssets{{{{",
        *rows, "}};", "", "} // namespace immune::platform::detail", "",
    ])
    write_if_changed(output / "EmbeddedAssetIndex.h", header)
    write_if_changed(output / "immune_assets.rc", "\n".join(rc_lines) + "\n")
    write_if_changed(output / "embedded_assets_manifest.json",
                     json.dumps(manifest, indent=2, ensure_ascii=True) + "\n")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", required=True, type=Path, help="repository root containing assets/")
    parser.add_argument("--output", required=True, type=Path, help="generated files directory")
    parser.add_argument("--notices", type=Path, help="combined third-party license notices to embed")
    args = parser.parse_args()
    manifest = generate(args.root, args.output, args.notices)
    print(f"Embedded {len(manifest)} files ({sum(row['bytes'] for row in manifest):,} bytes)")


if __name__ == "__main__":
    main()
